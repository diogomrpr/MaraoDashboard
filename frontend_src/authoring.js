// Only the deliberately small schema vocabulary generated by authoring-schema is used here.
function shapeErrors(value,schema,path) {
  if(schema.anyOf&&!schema.anyOf.some(option=>!shapeErrors(value,option,path).length))return [fail(path,'Value does not match a supported configuration shape.')];
  const errors=[],type=value===null?'null':Array.isArray(value)?'array':typeof value;
  if(schema.type&&![schema.type].flat().some(expected=>expected===type||expected==='integer'&&Number.isInteger(value)))return [fail(path,'Expected '+[schema.type].flat().join(' or ')+'.')];
  if(Object.hasOwn(schema,'const')&&!same(value,schema.const)||schema.enum&&!schema.enum.some(choice=>same(value,choice)))errors.push(fail(path,'Choose a supported value.'));
  if(typeof value==='number'&&(schema.minimum!==undefined&&value<schema.minimum||schema.maximum!==undefined&&value>schema.maximum)||typeof value==='string'&&schema.pattern&&!new RegExp(schema.pattern).test(value))errors.push(fail(path,'Value is outside the supported range or format.'));
  if(object(value)) {
    for(const key of schema.required||[])if(!Object.hasOwn(value,key))errors.push(fail(path+'/'+escape(key),'Required field is missing.'));
    for(const [key,child]of Object.entries(schema.properties||{}))if(Object.hasOwn(value,key))errors.push(...shapeErrors(value[key],child,path+'/'+escape(key)));
  }
  if(Array.isArray(value)&&schema.items)value.forEach((item,index)=>errors.push(...shapeErrors(item,schema.items,path+'/'+index)));
  return errors;
}
function cardEntries(document) {
  return popupDashboardCards(document).filter(entry=>typeof entry.config.type==='string').map(({config:card,address})=>({card,address}));
}
function inspect(document,context={}) {
  const diagnostics=[];
  if(!object(context)||context.entities!==undefined&&!Array.isArray(context.entities))return {diagnostics:[fail('/context','Supply an entity metadata array.')],ownership:[]};
  if(!object(document)||document.strategy||!Array.isArray(document.views))return {diagnostics:[fail('','Use an ordinary Home Assistant dashboard with views.')],ownership:[]};
  const paths=new Set();
  document.views.forEach((view,index)=>{
    if(!object(view)){diagnostics.push(fail('/views/'+index,'Each view must be an object.'));return;}
    for(const key of ['cards','sections','badges'])if(Object.hasOwn(view,key)&&!Array.isArray(view[key]))diagnostics.push(fail('/views/'+index+'/'+key,'Expected an array.'));
    if(Array.isArray(view.cards)&&view.cards.some(card=>!object(card)))diagnostics.push(fail('/views/'+index+'/cards','Cards must be objects.'));
    for(const [i,section]of (Array.isArray(view.sections)?view.sections:[]).entries())if(!object(section)||Object.hasOwn(section,'cards')&&(!Array.isArray(section.cards)||section.cards.some(card=>!object(card))))diagnostics.push(fail('/views/'+index+'/sections/'+i,'Use a section with a card array.'));
    const path=String(view.path??index);if(paths.has(path))diagnostics.push(fail('/views/'+index+'/path','View path is ambiguous.'));paths.add(path);
    const error=managedPopupError(view);if(error)diagnostics.push(fail('/views/'+index+'/marao_popup',error));
  });
  if(diagnostics.length)return {diagnostics,ownership:[]};
  if(Object.hasOwn(document,'marao'))try{validateDashboardSettings(document.marao);}catch(error){diagnostics.push(fail('/marao',error.message));}
  for(const {card,address}of cardEntries(document)) {
    if(!card.type.startsWith('custom:marao-'))continue;
    const path=pointer(address),definition=metadata.cards.find(item=>item.type===card.type);
    if(!definition){diagnostics.push(fail(path+'/type','Unsupported Marao card type.'));continue;}
    diagnostics.push(...shapeErrors(card,definition.schema,path));
    try {
      if(card.type==='custom:marao-card') {
        const descriptor=canonicalCard(copy(card)),template=canonicalTemplate(descriptor.template);
        if(template==='md_popup_card'||template==='md_navbar_card')continue;
        validateNativeCardConfig({...descriptor,type:nativeCardType(template),template},context.entities||[]);
      }else if(templateForNativeType(card.type))validateNativeCardConfig(card,context.entities||[]);
      else if(['custom:marao-camera-events-card','custom:marao-frigate-events-card'].includes(card.type))normalizeEventSources(card);
      else if(card.type==='custom:marao-navbar-card')validateDashboardSettings({version:1,navbar:card});
      if(card.popup_view)resolvePopupView(document,card.popup_view);
    }catch(error){diagnostics.push(fail(path,error.message));}
  }
  let ownership=[];
  try {
    ownership=popupOwners(document).map(binding=>({owner:pointer(binding.address),source:binding.path||null,external:binding.external,managed:Boolean(binding.path&&document.views.find((view,index)=>String(view.path??index)===binding.path)?.marao_popup),...(binding.error?{error:binding.error}:{})}));
    for(const binding of ownership)if(binding.error)diagnostics.push(fail(binding.owner,binding.error));
  }catch(error){diagnostics.push(fail('/views',error.message));}
  return {diagnostics,ownership};
}
const result=inspection=>({authoring_contract:metadata.authoring_contract,package_version:metadata.package_version,valid:!inspection.diagnostics.length,...inspection});
export function validateDashboard({config,context={}}={}) {
  try{return result(inspect(config,context));}catch(error){return result({diagnostics:[fail('',error.message)],ownership:[]});}
}
export function dashboardPatch(original,proposed) {
  const diff=(before,after,path='')=>{
    if(same(before,after))return [];
    if(!object(before)||!object(after))return [{op:'replace',path,value:copy(after)}];
    const patch=[];
    for(const key of Object.keys(before))if(!Object.hasOwn(after,key))patch.push({op:'remove',path:path+'/'+escape(key)});
    for(const [key,value]of Object.entries(after)) {
      const at=path+'/'+escape(key);
      if(!Object.hasOwn(before,key))patch.push({op:'add',path:at,value:copy(value)});
      else patch.push(...diff(before[key],value,at));
    }
    return patch;
  };
  let patch=diff(original,proposed);
  if(patch.length>100) {
    patch=[];
    for(const key of new Set([...Object.keys(original),...Object.keys(proposed)])) {
      const path='/'+escape(key);
      if(!Object.hasOwn(proposed,key))patch.push({op:'remove',path});
      else if(!Object.hasOwn(original,key))patch.push({op:'add',path,value:copy(proposed[key])});
      else if(!same(original[key],proposed[key]))patch.push({op:'replace',path,value:copy(proposed[key])});
    }
  }
  if(patch.length>100)throw new Error('The plan exceeds 100 patch operations. Narrow the requested edit.');
  return patch;
}
function atPointer(document,path) {
  if(typeof path!=='string'||!/^\/views\/\d+\//.test(path)||/~(?:[^01]|$)/.test(path))throw new Error('Choose an exact popup owner JSON Pointer under /views.');
  const parts=path.slice(1).split('/').map(part=>part.replaceAll('~1','/').replaceAll('~0','~'));
  let value=document;
  for(const key of parts){if(!object(value)&&!Array.isArray(value)||!Object.hasOwn(value,key))throw new Error('Popup owner path does not exist.');value=value[key];}
  return {value,parts};
}
export function planDashboardEdit(request={}) {
  let inspection={diagnostics:[],ownership:[]};
  try {
    const {original,proposed,config_hash,context,popup_edits=[]}=request;
    if(!object(context)||!Array.isArray(context.entities)||context.entities.some(entity=>!object(entity)||typeof entity.entity_id!=='string'))throw new Error('Supply context.entities as an explicit array of entity metadata.');
    if(typeof context.dashboardRoot!=='string'||! /^[a-z0-9][a-z0-9_-]*$/.test(context.dashboardRoot))throw new Error('Supply context.dashboardRoot for the owning dashboard.');
    if(typeof config_hash!=='string'||!config_hash.trim())throw new Error('Supply the unchanged config_hash from a fresh MCP read.');
    if(!Array.isArray(popup_edits)||popup_edits.some(path=>typeof path!=='string'))throw new Error('popup_edits must be an array of owner JSON Pointers.');
    if(!object(original)||original.strategy||!Array.isArray(original.views)||original.views.some(view=>!object(view)))throw new Error('Supply the complete original ordinary dashboard.');
    if(Object.hasOwn(original,'marao'))validateDashboardSettings(original.marao);
    for(const view of original.views){const error=managedPopupError(view);if(error)throw new Error(error);}
    inspection=inspect(proposed,context);if(inspection.diagnostics.length)return result(inspection);
    for(const view of proposed.views)if(view.marao_popup) {
      const prior=original.views.find((item,index)=>String(item.path??index)===String(view.path??proposed.views.indexOf(view)));
      if(!prior||!same(prior.marao_popup,view.marao_popup))throw new Error('Preserve popup management metadata; request popup creation through popup_edits.');
    }
    const available=new Set(context.entities.map(entity=>entity.entity_id)),required=new Set();
    for(const {card}of cardEntries(proposed))if(metadata.cards.some(item=>item.type===card.type)&&!['custom:marao-popup-card','custom:marao-control-grid'].includes(card.type)) {
      const id=card.entity_id||card.entity;if(typeof id==='string'&&/^[a-z0-9_]+\.[a-z0-9_]+$/.test(id))required.add(id);
      for(const member of Array.isArray(card.entities)?card.entities:[]){const memberId=typeof member==='string'?member:member?.entity_id;if(memberId)required.add(memberId);}
      for(const source of Array.isArray(card.cameras)?card.cameras:[])if(source?.entity)required.add(source.entity);
    }
    const missing=[...required].filter(id=>!available.has(id));
    if(missing.length)throw new Error('Supply context.entities metadata for: '+missing.join(', '));
    let config=copy(proposed);
    for(const path of new Set(popup_edits)) {
      const {value:owner,parts}=atPointer(config,path),entry=cardEntries(config).find(item=>pointer(item.address)===path);
      if(!entry||!object(owner)||!managedDescriptor(owner).template)throw new Error('Choose a supported popup owner.');
      const view=config.views[Number(parts[1])],viewPath=String(view.path??parts[1]);
      config=planPopupEdit(config,owner,viewPath,'/'+context.dashboardRoot+'/'+viewPath,context).config;
    }
    config=planManagedPopups(config,context);
    inspection=inspect(config,context);if(inspection.diagnostics.length)return result(inspection);
    const patch=dashboardPatch(original,config);
    return {...result(inspection),config_hash,config,patch};
  }catch(error){return result({...inspection,diagnostics:[...inspection.diagnostics,fail('',error.message)]});}
}
