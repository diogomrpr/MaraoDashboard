const object=value=>value!==null&&typeof value==='object'&&!Array.isArray(value),copy=value=>structuredClone(value),same=(a,b)=>popupCanonical(a)===popupCanonical(b);
const escape=value=>String(value).replaceAll('~','~0').replaceAll('/','~1');
