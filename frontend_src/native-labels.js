export function editorLabel(label, hass) {
  const language = String(hass?.locale?.language || hass?.language || "en").toLowerCase().split("-")[0];
  const reading = /^Reading ([123])( name| icon)?$/.exec(label);
  if (language === "pt" && reading) return "Leitura " + reading[1] + ({" name": " nome", " icon": " ícone"}[reading[2]] || "");
  return language === "pt" && labels[label] ? labels[label] : sharedLabel(label, hass);
}
