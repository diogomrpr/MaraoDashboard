function localize(key, hassOrLanguage, placeholders = {}) {
  const language = normalizeLanguage(hassOrLanguage);
  const catalog = TRANSLATIONS[language] || TRANSLATIONS.en;
  const text = catalog[key] || TRANSLATIONS.en[key] || key;
  return text.replace(/\{(\w+)\}/g, (_match, name) =>
    Object.prototype.hasOwnProperty.call(placeholders, name) ? placeholders[name] : `{${name}}`
  );
}

const POPUP_SCROLL_GUARD_VERSION = 2;
const MARAO_TEXT_SCALE_ATTRIBUTE = "data-marao-dashboard-text-scale";
const MARAO_TAP_DRAG_THRESHOLD = 10;
const MARAO_TAP_BLOCK_MS = 500;

function isMaraoDashboardPath(pathname) {
  const root = String(pathname || "").split("/")[1];
  return Boolean(root?.startsWith("marao-") && root !== "marao-dashboard-editor");
}

function syncMaraoTextScale(documentRoot = document, pathname = window.location.pathname) {
  const head = documentRoot.head;
  if (!head) return false;

  const owned = head.querySelector(`meta[${MARAO_TEXT_SCALE_ATTRIBUTE}]`);
  if (!isMaraoDashboardPath(pathname)) {
    owned?.remove();
    return false;
  }

  const existing = head.querySelector('meta[name="text-scale"]');
  if (existing && existing !== owned) {
    owned?.remove();
    return existing.getAttribute("content") === "scale";
  }
  if (owned) return true;

  const meta = documentRoot.createElement("meta");
  meta.setAttribute("name", "text-scale");
  meta.setAttribute("content", "scale");
  meta.setAttribute(MARAO_TEXT_SCALE_ATTRIBUTE, "");
  head.append(meta);
  return true;
}

function installMaraoTextScale() {
  const sync = () => syncMaraoTextScale();
  sync();
  window.addEventListener("location-changed", sync);
  window.addEventListener("popstate", sync);
}

function installMaraoTapGuard(eventRoot = window) {
  let gesture;
  let blockTapUntil = 0;

  const touchById = (event) => {
    const touches = [...(event.touches || []), ...(event.changedTouches || [])];
    return touches.find((touch) => touch.identifier === gesture?.identifier);
  };
  const start = (event) => {
    if (!isMaraoDashboardPath(eventRoot.location.pathname)) return;
    const touch = event.touches?.[0] || event.changedTouches?.[0];
    if (!touch) return;
    blockTapUntil = 0;
    gesture = {
      identifier: touch.identifier,
      x: touch.clientX,
      y: touch.clientY,
      dragged: (event.touches?.length || 0) > 1,
    };
  };
  const move = (event) => {
    const touch = touchById(event);
    if (!gesture || !touch) return;
    const x = touch.clientX - gesture.x;
    const y = touch.clientY - gesture.y;
    if (x * x + y * y >= MARAO_TAP_DRAG_THRESHOLD * MARAO_TAP_DRAG_THRESHOLD) {
      gesture.dragged = true;
    }
  };
  const finish = () => {
    if (gesture?.dragged) blockTapUntil = Date.now() + MARAO_TAP_BLOCK_MS;
    gesture = undefined;
  };
  const blockAccidentalTap = (event) => {
    if (!isMaraoDashboardPath(eventRoot.location.pathname) || Date.now() > blockTapUntil) return;
    if (event.type === "action" && event.detail?.action !== "tap") return;
    event.preventDefault();
    event.stopImmediatePropagation();
  };

  eventRoot.addEventListener("touchstart", start, { capture: true, passive: true });
  eventRoot.addEventListener("touchmove", move, { capture: true, passive: true });
  eventRoot.addEventListener("touchend", finish, { capture: true, passive: true });
  eventRoot.addEventListener("touchcancel", finish, { capture: true, passive: true });
  eventRoot.addEventListener("action", blockAccidentalTap, { capture: true });
  eventRoot.addEventListener("click", blockAccidentalTap, { capture: true });
}

