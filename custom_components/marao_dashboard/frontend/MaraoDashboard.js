function installPopupScrollGuard() {
  if (window.MaraoDashboard?.popupScrollGuardVersion === POPUP_SCROLL_GUARD_VERSION) return;

  let lastTouchY = 0;
  const isElement = (value) => value instanceof Element || value instanceof ShadowRoot;
  const isPopupElement = (value) =>
    value instanceof Element &&
    (value.classList.contains("bubble-pop-up") ||
      value.classList.contains("bubble-pop-up-container"));

  const hasOpenPopup = () => Boolean(window.location.hash);
  const isSlideToOpen = (element) => element instanceof HTMLElement && element.tagName === "MARAO-SLIDE-TO-OPEN";

  const scrollableFromPath = (path) =>
    path.find((element) => {
      if (!(element instanceof Element)) return false;
      const overflowY = window.getComputedStyle(element).overflowY;
      return (
        element.scrollHeight > element.clientHeight + 1 &&
        (element.classList.contains("bubble-pop-up") || ["auto", "scroll"].includes(overflowY))
      );
    });

  const canScroll = (element, deltaY) => {
    if (!element || !deltaY) return false;
    if (deltaY < 0) return element.scrollTop > 0;
    return element.scrollTop + element.clientHeight < element.scrollHeight - 1;
  };

  const block = (event) => {
    event.preventDefault();
    event.stopPropagation();
  };

  const guardScroll = (event) => {
    if (!hasOpenPopup()) return;

    const path = event.composedPath?.().filter(isElement) || [];
    if (path.some(isSlideToOpen)) return;
    const popupIndex = path.findIndex(isPopupElement);
    if (popupIndex < 0) {
      block(event);
      return;
    }
    const popupPath = path.slice(0, popupIndex + 1);

    const deltaY =
      event.type === "wheel"
        ? event.deltaY
        : lastTouchY - (event.touches?.[0]?.clientY ?? lastTouchY);
    if (!canScroll(scrollableFromPath(popupPath), deltaY)) {
      block(event);
      return;
    }
    event.stopPropagation();
  };

  window.addEventListener(
    "touchstart",
    (event) => {
      if (hasOpenPopup()) lastTouchY = event.touches?.[0]?.clientY ?? 0;
    },
    { capture: true, passive: true }
  );
  window.addEventListener("touchmove", guardScroll, { capture: true, passive: false });
  window.addEventListener("wheel", guardScroll, { capture: true, passive: false });
}

